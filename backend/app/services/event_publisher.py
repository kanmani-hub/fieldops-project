from app.services.websocket_tenant_filter import is_valid_tenant_id

logger = logging.getLogger(__name__)


def _has_valid_event_tenant(event_type: str, tenant_id: Optional[str]) -> bool:
    """Validate that outbound domain events carry a non-wildcard tenant_id."""
    if not is_valid_tenant_id(tenant_id):
        logger.warning(
            "Skipping publish of event=%s due to missing or invalid tenant_id.",
            event_type,
        )
        return False
    return True


def generate_idempotency_key(
    domain: str,
    tenant_id: str,
    aggregate_id: str,
    event_type: str,
    qualifier: Optional[str] = None,
) -> str:
    """
    Generate a deterministic, stable idempotency key for business events across
    producer and consumer boundaries.
    """
    norm_domain = (domain or "default").lower().strip()
    norm_tenant = (tenant_id or "default").lower().strip()
    norm_agg = str(aggregate_id or "unknown").strip()
    norm_type = (event_type or "event").lower().strip()
    if qualifier:
        return f"idem:{norm_domain}:{norm_tenant}:{norm_agg}:{norm_type}:{str(qualifier).strip().lower()}"
    return f"idem:{norm_domain}:{norm_tenant}:{norm_agg}:{norm_type}"


def publish_dispatch_event(
    redis_client,
    event_type: str,
    job_id: str,
    old_status: str = "UNKNOWN",
    new_status: str = "UNKNOWN",
    tenant_id: str = "default",
    technician_id: Optional[str] = None,
    technician_name: Optional[str] = None,
    completed_at: Optional[datetime] = None,
    correlation_id: Optional[str] = None,
    event_id: Optional[str] = None,
    idempotency_key: Optional[str] = None,
    schema_version: int = 1,
):
    """
    Publish a canonical dispatch event after successful persistence.

    For completion events, completed_at is the authoritative timestamp
    generated by the JobStatusMachine.

    event_id is deterministic for a persisted completion so downstream
    consumers have a stable idempotency key.
    """
    if not redis_client:
        logger.warning(
            "Redis client unavailable; skipping dispatch event publish."
        )
        return

    if not _has_valid_event_tenant(event_type, tenant_id):
        return

    if completed_at is not None:
        if completed_at.tzinfo is None:
            raise ValueError("completed_at must be timezone-aware")

        timestamp = (
            completed_at
            .astimezone(timezone.utc)
            .isoformat()
            .replace("+00:00", "Z")
        )
    else:
        timestamp = (
            datetime.now(timezone.utc)
            .isoformat()
            .replace("+00:00", "Z")
        )

    event_id = event_id or f"{event_type}:{tenant_id}:{job_id}"
    idempotency_key = idempotency_key or generate_idempotency_key(
        domain="dispatch",
        tenant_id=tenant_id,
        aggregate_id=job_id,
        event_type=event_type,
        qualifier=new_status if new_status != "UNKNOWN" else None,
    )

    payload = {
        # Keep legacy key for existing WebSocket consumers.
        "event": event_type,

        # Canonical event contract.
        "event_type": event_type.lower(),
        "event_id": event_id,
        "idempotency_key": idempotency_key,
        "schema_version": schema_version,
        "job_id": str(job_id),
        "status": new_status,
        "old_status": old_status,
        "new_status": new_status,
        "timestamp": timestamp,
        "tenant_id": str(tenant_id),
    }

    if correlation_id:
        payload["correlation_id"] = correlation_id

    if technician_id and technician_name:
        payload["technician"] = {
            "tech_id": technician_id,
            "name": technician_name,
        }

    try:
        redis_client.publish(
            "dispatch_events",
            json.dumps(payload),
        )

        logger.info(
            "Published %s for job %s to dispatch_events channel.",
            event_type,
            job_id,
        )

    except Exception as e:
        logger.error(
            "Failed to publish dispatch event to Redis: %s",
            e,
        )


